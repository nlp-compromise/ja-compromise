// a gold-standard for word-segmentation.
//
// each line is a sentence, with a | where a term ends and the next begins.
// punctuation and spaces are ignored, so it doesn't matter which side of a
// comma the | goes on.  ../gold.hmm.js scores the tokenizer against it - `npm run test:hmm`.
//
// these are the answers we *want*, not the ones we get - don't change a line
// here to make a test pass.  change one only when it breaks these rules:
//
//  1. a particle is its own term, and so is each particle in a stack of them
//     - に|は, で|の, か|も.  と|いう, に|ついて and と|して are a particle and a verb.
//  2. a verb or adjective keeps its bound endings - 食べました, 行かなければ,
//     高くない, 食べさせられたくなかった, and the contractions 食べちゃった, 見てる.
//  3. a て-form and the helper verb after it are two terms - 読んで|いる,
//     書いて|あります, 食べて|ください.
//  4. the copula is its own term - 学生|です, 学生|じゃない, 先生|ではありません.
//  5. a する-noun and its する are one verb - 勉強します, 検索する.
//     a verb made of two verbs is one verb too - 走り出した, 食べすぎた.
//  6. a number and its counter are two terms - 3|人, 2024|年.  the number
//     itself is one, however it's written - 二十三, 1,000, 3万5千.
//  7. a compound noun is split between its words, when each could stand alone
//     - 自然|言語|処理, 東京|大学.  a one-kanji prefix or suffix stays on its
//     word - 大学生, 外国人, 東京都, 理事会.  a family-name and a given-name
//     are two terms - 田中|太郎.
//  8. さん is its own term - 田中|さん.  たち, お and ご are part of the word -
//     私たち, お茶, ご飯.
//  9. an adjective's adverb-form is one term - 高く, 静かに.
//     but 静か|な is two.
// 10. a run of katakana is one term - ニュージーランド.

